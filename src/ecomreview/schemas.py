"""Data contracts and Pydantic schemas for the EcomReview AI pipeline."""

from enum import Enum
from typing import Optional

from pydantic import BaseModel, Field


class MacroAspect(str, Enum):
    """Macro-level aspect categories for cross-domain evaluation."""

    PERFORMANCE_FUNCTION = "PERFORMANCE_FUNCTION"
    QUALITY_DESIGN = "QUALITY_DESIGN"
    PRICE_VALUE = "PRICE_VALUE"
    SERVICE_LOGISTICS = "SERVICE_LOGISTICS"
    GENERAL = "GENERAL"


class Aspect(str, Enum):
    """Fine-grained aspects for e-commerce raincoat domain."""

    WATERPROOF = "WATERPROOF"
    MATERIAL_DURABILITY = "MATERIAL_DURABILITY"
    FIT_SIZE = "FIT_SIZE"
    COMFORT_USABILITY = "COMFORT_USABILITY"
    PRICE_VALUE = "PRICE_VALUE"
    PACKAGING_SHIPPING = "PACKAGING_SHIPPING"
    CUSTOMER_SERVICE = "CUSTOMER_SERVICE"
    ACCESSIBILITY_DESIGN = "ACCESSIBILITY_DESIGN"
    GENERAL = "GENERAL"

    # Aliases for backward/cross-domain compatibility
    LOGISTICS = "PACKAGING_SHIPPING"
    SERVICE = "CUSTOMER_SERVICE"
    ACCURACY_DESIGN = "ACCESSIBILITY_DESIGN"


FINE_TO_MACRO_ASPECT: dict[Aspect, MacroAspect] = {
    Aspect.WATERPROOF: MacroAspect.PERFORMANCE_FUNCTION,
    Aspect.COMFORT_USABILITY: MacroAspect.PERFORMANCE_FUNCTION,
    Aspect.MATERIAL_DURABILITY: MacroAspect.QUALITY_DESIGN,
    Aspect.FIT_SIZE: MacroAspect.QUALITY_DESIGN,
    Aspect.ACCESSIBILITY_DESIGN: MacroAspect.QUALITY_DESIGN,
    Aspect.PRICE_VALUE: MacroAspect.PRICE_VALUE,
    Aspect.PACKAGING_SHIPPING: MacroAspect.SERVICE_LOGISTICS,
    Aspect.CUSTOMER_SERVICE: MacroAspect.SERVICE_LOGISTICS,
    Aspect.GENERAL: MacroAspect.GENERAL,
}


class Polarity(str, Enum):
    """Sentiment polarity categories."""

    POS = "positive"
    NEG = "negative"
    NEU = "neutral"


class AspectOpinion(BaseModel):
    """Extracted aspect opinion with verbatim evidence."""

    aspect: Aspect = Field(description="Aspect category being evaluated")
    polarity: Polarity = Field(description="Sentiment polarity for this aspect")
    evidence: str = Field(description="Verbatim quote from original review as evidence, 1-15 words")


class ReviewAnalysis(BaseModel):
    """Structured output schema returned by the LLM / ABSA Analyzer."""

    overall_sentiment: Polarity = Field(description="Dominant sentiment of the entire review")
    opinions: list[AspectOpinion] = Field(
        default_factory=list, description="List of aspect opinions extracted"
    )
    informative: bool = Field(
        description="True if review has specific product/service info; False if pure spam/generic"
    )


class ActionType(str, Enum):
    """Types of actionable proposals generated by the agent."""

    # Marketing Actions (is_marketing = True)
    LISTING_UPDATE = "LISTING_UPDATE"
    CONTENT = "CONTENT"
    REVIEW_REPLY = "REVIEW_REPLY"
    PROMOTION = "PROMOTION"
    CUSTOMER_CARE = "CUSTOMER_CARE"

    # Operational / Product Actions (is_marketing = False)
    PRODUCT_FIX = "PRODUCT_FIX"
    OPS = "OPS"


class ActionProposal(BaseModel):
    """Actionable proposal generated by the Action Planner."""

    action_id: str = Field(description="Unique action proposal identifier (e.g. act_001)")
    action_type: ActionType = Field(description="Category of action")
    is_marketing: bool = Field(description="True if marketing action; False if ops/product")
    title: str = Field(description="Concise summary title of the proposed action")
    description: str = Field(description="Detailed step-by-step description of what to execute")
    insight_ids: list[str] = Field(
        default_factory=list,
        description="List of valid insight IDs that substantiate this proposal",
    )
    evidence_review_ids: list[str] = Field(
        default_factory=list,
        min_length=2,
        description="At least 2 real review IDs from dataset serving as ground truth evidence",
    )
    target_metric: str = Field(description="Target business or rating metric to improve")
    priority: str = Field(
        default="MEDIUM",
        description="Execution priority: HIGH, MEDIUM, LOW",
    )


class CriticFeedback(BaseModel):
    """Evaluation feedback generated by the Hybrid Critic (R1-R7 rules + LLM)."""

    passed: bool = Field(description="True if proposal passes all guardrails and quality checks")
    rule_violations: list[str] = Field(
        default_factory=list,
        description="List of violated deterministic rules (R1-R7) or LLM critique notes",
    )
    score: float = Field(
        ge=0.0,
        le=5.0,
        description="Rubric evaluation score (1.0 - 5.0)",
    )
    suggestions: Optional[str] = Field(
        default=None,
        description="Concrete modification suggestions for the planner loop",
    )


